"""Generates wm20/src/fps_tail_table.h from research/fps_tail.json (group A per-tick patches)."""
import json, sys, struct
src, out = sys.argv[1], sys.argv[2]
L = json.load(open(src))
TYPES = {'f32': 'RT_F32', 'i8': 'RT_I8', 'i16': 'RT_I16', 'i32': 'RT_I32', 'ptr_f32': 'RT_PTR'}
groups = {}
rows, raws = [], []
def hb(s): return [int(b, 16) for b in s.split()]
for x in L:
    va = int(x['va'], 16)
    orig = hb(x['orig'])
    g = x.get('pair_group')
    gid = groups.setdefault(g, len(groups) + 1) if g else 0
    if 'explicit' in x:
        ex = x['explicit']
        sites = {}
        for rate in ('60', '120', '180'):
            for a, b in ex[rate].items():
                sites.setdefault(a, {})[rate] = hb(b)
        po = x['pair'].split(' ', 1)
        origs = {x['va']: orig, po[0]: hb(po[1])}
        for a, per in sites.items():
            o = origs[a]
            raws.append((int(a, 16), o, [per['60'], per['120'], per['180']], x['area']))
        continue
    t = TYPES[x['operand_type']]
    vals = [x['new'][r] for r in ('60', '120', '180')]
    if t in ('RT_I8', 'RT_I16', 'RT_I32'):
        vals = [int(round(v)) for v in vals]
        if t == 'RT_I8':
            assert -128 <= vals[0] <= 127, x  # 60 must fit; 120 / 180 clamp (imm8 operands, e.g. imul r,r,1Eh)
            if not all(-128 <= v <= 127 for v in vals):
                print('clamped imm8 at', x['va'], vals)
                vals = [max(-128, min(127, v)) for v in vals]
        if t == 'RT_I16':
            assert all(-32768 <= v <= 32767 for v in vals), x
    rows.append((va, x['operand_offset'], t, orig, vals, gid, x['area'], int(x.get('const_va', '0'), 16) if t == 'RT_PTR' else 0))
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by gen_tail.py from research/fps_tail.json (%d group-A sites): do not edit by hand.\n' % (len(rows) + len(raws)))
    f.write('// {site, operand offset, type, original bytes length, original bytes, values at 60 / 120 / 180, pair group}\n')
    f.write('static const RateTail kTail[] = {\n')
    for va, off, t, orig, vals, gid, area, cva in rows:
        ob = ', '.join('0x%02X' % b for b in orig)
        if t in ('RT_F32', 'RT_PTR'):
            vs = ', '.join(repr(float(v)) + 'f' if 'e' not in repr(float(v)) else '%.9ef' % v for v in vals)
            vs = ', '.join(('%.9g' % v) + ('f' if ('.' in '%.9g' % v or 'e' in '%.9g' % v) else '.0f') for v in vals)
        else:
            vs = ', '.join('%d' % v for v in vals)
        f.write('    { 0x%06X, %d, %s, %d, { %s }, { %s }, %d },  // %s\n' % (va, off, t, len(orig), ob, vs, gid, area))
    f.write('};\n')
    f.write('static const RateRaw kTailRaw[] = {\n')
    for va, o, per, area in raws:
        f.write('    { 0x%06X, %d, { %s }, { { %s }, { %s }, { %s } } },  // %s\n' % (va, len(o), ', '.join('0x%02X' % b for b in o),
                ', '.join('0x%02X' % b for b in per[0]), ', '.join('0x%02X' % b for b in per[1]), ', '.join('0x%02X' % b for b in per[2]), area))
    f.write('};\n')
print(len(rows), 'rows,', len(raws), 'raw,', len(groups), 'pair groups')
